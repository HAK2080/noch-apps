export function posLanguage(value) {
  return value === 'en' ? 'en' : 'ar'
}

export function savedPosLanguage() {
  try { return posLanguage(localStorage.getItem('pos-tile-lang')) } catch { return 'ar' }
}

export function posMessage(message, lang = 'ar', values = {}) {
  const template = posLanguage(lang) === 'ar' ? (POS_MESSAGES_AR[message] || message) : message
  return template.replace(/\{(\w+)\}/g, (match, key) => String(values[key] ?? match))
}

// Do not expose raw English database/transport errors to the cashier. Callers
// keep diagnostics in the console; unknown errors use an action-specific message.
export function posError(error, fallback, lang = 'ar') {
  const raw = typeof error === 'string' ? error : error?.message || ''
  if (posLanguage(lang) === 'en') return raw || fallback
  if (POS_MESSAGES_AR[raw]) return posMessage(raw, lang)
  const known = [
    [/fetch|network|timeout|timed out|connection/i, 'Network unavailable. Check your connection and try again.'],
    [/jwt|session expired|not authenticated/i, 'Session expired. Sign in again.'],
    [/identity exception|multiple.*(customer|account)/i, 'Ask the manager to resolve this account match.'],
    [/insufficient.*points|not enough.*points/i, 'Not enough loyalty points.'],
    [/reward.*(expired|unavailable|not available)/i, 'Reward expired or unavailable.'],
  ].find(([pattern]) => pattern.test(raw))
  return posMessage(known?.[1] || fallback, lang)
}
